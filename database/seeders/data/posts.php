<p>El artículo 52 del CPACA establece que la facultad de la administración para imponer sanciones <strong>caduca a los tres años</strong> contados desde el día de la infracción. Y una vez impuesta la sanción, el cobro también prescribe a los tres años.</p>
<p>Hay comparendos durmiendo en el sistema que aparecen cuando vas a hacer un trámite. Si la fecha de la infracción supera tres años, procede el archivo.</p>

<h2>Regla 3: deben tener la prueba</h2>
<p>La entidad está obligada a conservar:</p>
<ul>
<li>La fotografía o el video donde la placa sea legible.</li>
<li>El certificado de calibración vigente del equipo.</li>
<li>El registro de la validación hecha por un agente de tránsito.</li>
<li>El soporte del envío de la notificación.</li>
</ul>
<p>Pedir estos documentos es parte de la estrategia: si no los tienen o están incompletos, el soporte de la sanción se cae.</p>

<h2>Caso especial: el carro que ya vendiste</h2>
<p>Si el traspaso estaba registrado en el RUNT cuando ocurrió la infracción, el comparendo no es tuyo. El problema aparece cuando el comprador no hizo el traspaso: ahí la multa llega a tu nombre y hay que probar la fecha real de la entrega.</p>
<p>Por eso una <a href="/documentos/promesa-de-compraventa-vehiculo">promesa de compraventa</a> con fecha cierta de entrega y cláusula de responsabilidad por multas vale mucho más de lo que cuesta.</p>

