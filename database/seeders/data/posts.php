<li>Mira la <strong>fecha de la infracción</strong> y la fecha de imposición del comparendo.</li>
<li>Calcula si han pasado más de tres años.</li>
<li>Revisa si alguna vez recibiste algo en tu domicilio registrado en el RUNT.</li>
